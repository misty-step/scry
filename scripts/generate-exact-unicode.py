#!/usr/bin/env python3
"""Reproduce exact-v2's Unicode 17 tables without a runtime dependency.

Download the named files from https://www.unicode.org/Public/17.0.0/ucd/
into a disposable directory, then pass that directory here. Inputs are pinned
by SHA-256; --check compares the generated bytes with the committed tables.
The Unicode data license is retained beside the generated tables.
"""

import argparse
import hashlib
from pathlib import Path


HASHES = {
    "UnicodeData.txt": "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c",
    "CaseFolding.txt": "ff8d8fefbf123574205085d6714c36149eb946d717a0c585c27f0f4ef58c4183",
    "DerivedNormalizationProps.txt": "71fd6a206a2c0cdd41feb6b7f656aa31091db45e9cedc926985d718397f9e488",
}


def verified_text(directory, name):
    data = (directory / name).read_bytes()
    if hashlib.sha256(data).hexdigest() != HASHES[name]:
        raise ValueError(f"Unexpected Unicode 17 bytes: {name}")
    return data.decode("utf-8")


def rust_char(code):
    return f"'\\u{{{code:x}}}'"


def rust_string(codes):
    return '"' + "".join(f"\\u{{{code:x}}}" for code in codes) + '"'


def ranges(codes):
    result = []
    for code in sorted(codes):
        if result and code == result[-1][1] + 1:
            result[-1] = (result[-1][0], code)
        else:
            result.append((code, code))
    return result


def generate(directory):
    records = {}
    categories = {"LETTER": set(), "MARK": set(), "PUNCTUATION": set(), "DASH": set()}
    first = None
    for line in verified_text(directory, "UnicodeData.txt").splitlines():
        fields = line.split(";")
        code = int(fields[0], 16)
        records[code] = fields
        if fields[1].endswith(", First>"):
            first = code
            continue
        start = first if fields[1].endswith(", Last>") else code
        first = None
        for name, prefix in [("LETTER", "L"), ("MARK", "M"), ("PUNCTUATION", "P"), ("DASH", "Pd")]:
            if fields[2].startswith(prefix):
                categories[name].update(range(start, code + 1))

    excluded = set()
    for line in verified_text(directory, "DerivedNormalizationProps.txt").splitlines():
        fields = line.split("#")[0].strip().split(";")
        if len(fields) < 2 or fields[1].strip() != "Full_Composition_Exclusion":
            continue
        ends = fields[0].strip().split("..")
        excluded.update(range(int(ends[0], 16), int(ends[-1], 16) + 1))

    decompositions = {}
    compositions = {}
    combining = {}
    for code, fields in records.items():
        if fields[3] != "0":
            combining[code] = int(fields[3])
        parts = fields[5].split()
        if not parts:
            continue
        compatible = parts[0].startswith("<")
        mapping = [int(part, 16) for part in parts[1 if compatible else 0:]]
        decompositions[code] = mapping
        if not compatible and len(mapping) == 2 and code not in excluded:
            compositions[tuple(mapping)] = code

    def decompose(code):
        syllable = code - 0xAC00
        if 0 <= syllable < 11172:
            result = [0x1100 + syllable // 588, 0x1161 + (syllable % 588) // 28]
            if syllable % 28:
                result.append(0x11A7 + syllable % 28)
            return result
        if code not in decompositions:
            return [code]
        return [part for child in decompositions[code] for part in decompose(child)]

    folds = {}
    for line in verified_text(directory, "CaseFolding.txt").splitlines():
        fields = line.split("#")[0].strip().split(";")
        if len(fields) > 2 and fields[1].strip() in {"C", "F"}:
            folds[int(fields[0], 16)] = [int(part, 16) for part in fields[2].split()]

    output = [
        "// Generated by scripts/generate-exact-unicode.py; do not edit.",
        "// Unicode 17.0.0; source hashes are pinned in that script.",
        "// SPDX-License-Identifier: Unicode-3.0; see UNICODE-LICENSE.txt.",
    ]

    def table(name, kind, rows):
        output.extend(["", "#[rustfmt::skip]", f"pub(super) static {name}: &[{kind}] = &["])
        output.extend(f"    {row}," for row in rows)
        output.append("];")

    table("DECOMPOSITION", "(char, &str)",
          (f"({rust_char(code)}, {rust_string(decompose(code))})" for code in sorted(decompositions)))
    table("COMPOSITION", "((char, char), char)",
          (f"(({rust_char(a)}, {rust_char(b)}), {rust_char(code)})"
           for (a, b), code in sorted(compositions.items())))
    table("COMBINING", "(char, u8)",
          (f"({rust_char(code)}, {value})" for code, value in sorted(combining.items())))
    table("CASE_FOLD", "(char, &str)",
          (f"({rust_char(code)}, {rust_string(mapping)})" for code, mapping in sorted(folds.items())))
    for name, codes in categories.items():
        table(name, "(char, char)",
              (f"({rust_char(a)}, {rust_char(b)})" for a, b in ranges(codes)))
    return "\n".join(output) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("directory", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = Path(__file__).resolve().parents[1] / "src/grading/unicode_tables.rs"
    generated = generate(args.directory)
    if args.check:
        if target.read_text() != generated:
            raise SystemExit("Unicode tables differ; regenerate and review")
        print("Unicode 17 tables: byte-identical")
    else:
        target.write_text(generated)
        print(f"Wrote {target}")


if __name__ == "__main__":
    main()
